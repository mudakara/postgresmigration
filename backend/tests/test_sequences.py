def test_trigger_assignments_are_found():
    uses = find_uses("""
        BEGIN
          -- NEW.ignored := nextval('commented_out');
          NEW.order_id := nextval('shop.order_seq');
          NEW."Line No" := COALESCE(NEW."Line No", nextval('line_seq'::regclass));
          SELECT nextval('audit_seq') INTO STRICT NEW.audit_id;
          RETURN NEW;
        END""")
    assert set(uses) == {
        SequenceUse(("shop", "order_seq"), "order_id", None, "trigger"),
        SequenceUse(("line_seq",), "Line No", None, "trigger"),
        SequenceUse(("audit_seq",), "audit_id", None, "trigger"),
    }


def test_insert_statements_map_nextval_to_its_column():
    uses = find_uses("""
        INSERT INTO shop.orders (customer_id, order_id, note)
        VALUES (p_customer, nextval('shop.order_seq'), 'it''s, (tricky)');
        INSERT INTO audit_log (msg, id) SELECT 'x', nextval('audit_seq') FROM dual_like WHERE true;
        INSERT INTO plain VALUES (nextval('no_column_list'));""")
    assert set(uses) == {
        SequenceUse(("shop", "order_seq"), "order_id", ("shop", "orders"), "insert"),
        SequenceUse(("audit_seq",), "id", ("audit_log",), "insert"),
    }


def state(next_last, *maxima, oracle=None, max_value=2**63 - 1):
    """next_last: the sequence's last_value, None when it has never been used."""
    s = SequenceState("s", "seq", "bigint", 1, 1, max_value, 1, next_last or 1, next_last is not None, True,
                      columns=[ColumnLink("s", "t", f"c{i}", "default", max_value=m) for i, m in enumerate(maxima)])
    evaluate([s], [{"owner": "S", "name": "SEQ", "last_number": oracle, "increment": 1}] if oracle else None)
    return s


def test_statuses():
    assert state(None, 50).status == "behind"  # never used: next is start (1)
    assert state(50, 50).status == "ok"  # next is 51
    assert state(49, 50).status == "behind" and state(49, 50).needed_next == 51
    assert state(100, 50).status == "ok"
    assert state(100, 50, oracle=500).status == "behind_oracle"
    assert state(100, 50, oracle=500).needed_next == 500
    assert state(100).status == "unlinked"
    assert state(10, 3_000_000_000, max_value=2_147_483_647).status == "overflow"


DDL = """
CREATE SCHEMA app;
-- 1. identity column loaded with explicit ids (OVERRIDING SYSTEM VALUE): behind
CREATE TABLE app.customers (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text);
INSERT INTO app.customers (id, name) SELECT g, 'c' || g FROM generate_series(1, 120) g;
-- 2. serial column used normally: ok
CREATE TABLE app.notes (id serial PRIMARY KEY, body text);
INSERT INTO app.notes (body) SELECT 'n' FROM generate_series(1, 5);
-- 3. Oracle style: sequence + BEFORE INSERT trigger, data loaded with the trigger disabled: behind
CREATE SEQUENCE app.orders_seq;
CREATE TABLE app.orders (order_id numeric(12) PRIMARY KEY, customer_id bigint);
INSERT INTO app.orders SELECT g, 1 FROM generate_series(1, 300) g;
CREATE FUNCTION app.orders_bi() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.order_id IS NULL THEN
    NEW.order_id := nextval('orders_seq');
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER orders_bi BEFORE INSERT ON app.orders FOR EACH ROW EXECUTE FUNCTION app.orders_bi();
-- 4. sequence used by a procedure's INSERT: behind
CREATE SEQUENCE app.log_seq;
CREATE TABLE app.log (log_id bigint PRIMARY KEY, msg text);
INSERT INTO app.log SELECT g, 'm' FROM generate_series(1, 42) g;
CREATE PROCEDURE app.write_log(p_msg text) LANGUAGE plpgsql AS $$
BEGIN
  INSERT INTO log (msg, log_id) VALUES (p_msg, nextval('app.log_seq'));
END $$;
-- 5. a sequence nothing uses
CREATE SEQUENCE app.spare_seq;
-- 6. integer sequence, data beyond its range
CREATE SEQUENCE app.small_seq AS integer;
CREATE TABLE app.big (id bigint DEFAULT nextval('app.small_seq') PRIMARY KEY);
INSERT INTO app.big VALUES (3000000000);
"""


@pytest.fixture
def migrated_db():
    s = get_settings()
    if not s.scratch_db_password:
        pytest.skip("scratch-pg is not configured")
    name = f"seq_{uuid.uuid4().hex[:8]}"
    admin = dict(host=s.scratch_db_host, port=s.scratch_db_port, user=s.scratch_db_user,
                 password=s.scratch_db_password, autocommit=True)
    with psycopg.connect(dbname=s.scratch_db_name, **admin) as conn:
        conn.execute(sql.SQL("CREATE DATABASE {} TEMPLATE template0").format(sql.Identifier(name)))
    with psycopg.connect(dbname=name, **admin) as conn:
        conn.execute(DDL)
    yield Endpoint(kind=DbKind.POSTGRES, host=s.scratch_db_host, port=s.scratch_db_port, database=name,
                   username=s.scratch_db_user, password=s.scratch_db_password, options={"sslmode": "disable"})
    with psycopg.connect(dbname=s.scratch_db_name, **admin) as conn:
        conn.execute(sql.SQL("DROP DATABASE IF EXISTS {} WITH (FORCE)").format(sql.Identifier(name)))


def run_check(client, session_factory, connection_id):
    resp = client.post("/api/sequence-checks", json={"postgres_connection_id": connection_id, "schemas": ["app"]})
    assert resp.status_code == 202, resp.text
    execute_job(uuid.UUID(resp.json()["job_id"]), session_factory)
    with session_factory() as s:
        job = s.get(Job, uuid.UUID(resp.json()["job_id"]))
        assert job.status is JobStatus.SUCCEEDED, job.error
    return client.get(f"/api/sequence-checks/{resp.json()['id']}").json()


def apply_script(ep: Endpoint, script: str) -> None:
    """What a DBA would do with psql -f (the app itself never writes)."""
    body = "\n".join(line for line in script.splitlines() if not line.startswith("\\"))
    with psycopg.connect(host=ep.host, port=ep.port, user=ep.username, password=ep.password,
                         dbname=ep.database, autocommit=True) as conn:
        conn.execute(body)


def test_check_finds_behind_sequences_and_the_script_fixes_them(client, session_factory, migrated_db):
    conn = client.post("/api/connections", json=endpoint_payload(migrated_db, "migrated")).json()
    check = run_check(client, session_factory, conn["id"])
    seqs = {s["name"]: s for s in check["sequences"]}

    assert seqs["customers_id_seq"]["status"] == "behind"
    assert seqs["customers_id_seq"]["columns"][0]["via"] == "identity"
    assert seqs["notes_id_seq"]["status"] == "ok" and seqs["notes_id_seq"]["columns"][0]["via"] == "serial"
    orders = seqs["orders_seq"]
    assert orders["status"] == "behind" and orders["needed_next"] == 301
    assert orders["columns"][0] | {"max_value": 300} == {**orders["columns"][0], "via": "trigger", "source": "app.orders_bi",
                                                         "table": "orders", "column": "order_id"}
    log = seqs["log_seq"]
    assert log["status"] == "behind" and log["columns"][0]["via"] == "insert" and log["columns"][0]["source"] == "app.write_log"
    assert seqs["spare_seq"]["status"] == "unlinked"
    assert seqs["small_seq"]["status"] == "overflow"
    assert check["summary"]["status"]["behind"] == 3

    script = client.get(f"/api/sequence-checks/{check['id']}/fix.sql").text
    assert "setval" in script and "spare_seq" not in script.split("-- Verify")[0]
    assert "ALTER SEQUENCE \"app\".\"small_seq\" AS bigint" in script

    # Rows added after the check are still covered: the script recomputes max() when run.
    ep = migrated_db
    with psycopg.connect(host=ep.host, port=ep.port, user=ep.username, password=ep.password,
                         dbname=ep.database, autocommit=True) as pg:
        pg.execute("INSERT INTO app.orders VALUES (310, 1)")
    apply_script(ep, script)
    apply_script(ep, script)  # idempotent

    after = {s["name"]: s for s in run_check(client, session_factory, conn["id"])["sequences"]}
    for name in ("customers_id_seq", "orders_seq", "log_seq"):
        assert after[name]["status"] == "ok", after[name]
    assert after["orders_seq"]["next_value"] == 311
    with psycopg.connect(host=ep.host, port=ep.port, user=ep.username, password=ep.password,
                         dbname=ep.database, autocommit=True) as pg:
        pg.execute("SET search_path = app, public")  # as the application's login would have
        pg.execute("INSERT INTO app.orders (customer_id) VALUES (1)")  # the trigger's nextval no longer collides
        pg.execute("CALL app.write_log('works')")
        pg.execute("INSERT INTO app.customers (name) VALUES ('new')")


def test_script_never_moves_a_sequence_backwards(client, session_factory, migrated_db):
    conn = client.post("/api/connections", json=endpoint_payload(migrated_db, "migrated")).json()
    ep = migrated_db
    with psycopg.connect(host=ep.host, port=ep.port, user=ep.username, password=ep.password,
                         dbname=ep.database, autocommit=True) as pg:
        pg.execute("SELECT setval('app.notes_id_seq', 1000)")
    check = run_check(client, session_factory, conn["id"])
    apply_script(ep, client.get(f"/api/sequence-checks/{check['id']}/fix.sql", params={"scope": "all"}).text)
    with psycopg.connect(host=ep.host, port=ep.port, user=ep.username, password=ep.password,
                         dbname=ep.database, autocommit=True) as pg:
        assert pg.execute("SELECT nextval('app.notes_id_seq')").fetchone()[0] == 1001


