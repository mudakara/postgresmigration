"""SQL script that moves sequences past the migrated data.

Each statement recomputes max() when it runs (rows may have been added since the check),
takes Oracle's value into account when known, and never moves a sequence backwards:

    SELECT setval('"s"."seq"'::regclass, GREATEST(
        (SELECT COALESCE(ceil(max("id")::numeric), 0)::bigint FROM "s"."t") + 1,
        123456,  -- Oracle S.SEQ LAST_NUMBER
        (SELECT CASE WHEN is_called THEN last_value + 1 ELSE last_value END FROM "s"."seq")
    ), false);  -- false: the next nextval() returns exactly this value

Safe to run more than once.
"""

from datetime import UTC, datetime
from typing import Any

FIXABLE = {"behind", "behind_oracle"}
LINKED = FIXABLE | {"ok", "check_failed"}


def qi(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def lit(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def statement(seq: dict[str, Any]) -> str | None:
    terms = []
    for c in seq["columns"]:
        if c.get("error") and "not numeric" in c["error"]:
            continue
        terms.append(
            f"    (SELECT COALESCE(ceil(max({qi(c['column'])})::numeric), 0)::bigint FROM {qi(c['schema'])}.{qi(c['table'])}) + 1,"
            f"  -- {c['via']}{' in ' + c['source'] if c.get('source') else ''}"
        )
    if seq.get("oracle"):
        o = seq["oracle"]
        terms.append(f"    {o['last_number']},  -- Oracle {o['owner']}.{o['name']} LAST_NUMBER")
    if not terms:
        return None
    target = f"{qi(seq['schema'])}.{qi(seq['name'])}"
    current = (f"    (SELECT CASE WHEN is_called THEN last_value + {int(seq['increment'])} ELSE last_value END FROM {target})"
               "  -- its own next value: never move backwards")
    name = lit(target)
    return f"SELECT setval({name}::regclass, GREATEST(\n" + "\n".join(terms) + f"\n{current}\n), false);"


def fix_script(seqs: list[dict[str, Any]], *, scope: str, connection: str, checked_at: datetime | None) -> str:
    """scope: "needed" (sequences found behind) or "all" (every linked sequence, as a re-sync)."""
    wanted = FIXABLE if scope == "needed" else LINKED
    chosen = [s for s in seqs if s["status"] in wanted]
    overflow = [s for s in seqs if s["status"] == "overflow"]
    lines = [
        f"-- Sequence fix for {connection}",
        f"-- Generated by Migration Studio on {datetime.now(UTC):%Y-%m-%d %H:%M} UTC"
        + (f" from the check of {checked_at:%Y-%m-%d %H:%M} UTC" if checked_at else ""),
        f"-- {len(chosen)} sequence(s): " + ("those found behind the data or Oracle." if scope == "needed"
                                              else "every sequence linked to a column or an Oracle sequence (re-sync)."),
        "--",
        "-- Run with a login that may update these sequences (owner, or UPDATE privilege), e.g.:",
        "--   psql -h <host> -p <port> -d <database> -U <owner> -f fix_sequences.sql",
        "-- Each statement recomputes max() when it runs and never moves a sequence backwards,",
        "-- so the script is safe to run again (for example after a later data load).",
        "-- setval() is not transactional: each statement takes effect immediately.",
        "",
        "\\set ON_ERROR_STOP on",
        "SET lock_timeout = '10s';",
        "",
    ]
    for s in chosen:
        stmt = statement(s)
        if stmt is None:
            continue
        lines += [f"-- {s['schema']}.{s['name']}: {s['status']}. {s['message']}", stmt, ""]
    if overflow:
        lines += ["-- These sequences cannot hold the values they need; widen them first, then re-run the check:"]
        for s in overflow:
            lines.append(f"--   ALTER SEQUENCE {qi(s['schema'])}.{qi(s['name'])} AS bigint MAXVALUE 9223372036854775807;"
                         f"  -- needs {s['needed_next']:,}, max {s['max_value']:,}")
        lines.append("")
    lines += [
        "-- To verify, run the sequence check again in Migration Studio: these should now show as OK.",
        "",
    ]
    return "\n".join(lines)
